def generate_rbac_matrix(config: dict, strings: dict) -> dict:
    """Generate RBAC permission matrix for all IDs.
    
    Returns:
    {
        "5t07c": { "view": ["admin","doctor","nurse"], "edit": ["admin","doctor"], "export": ["admin"] },
        ...
    }
    """
    ids = config.get("ids", {})
    matrix = {}
    
    # Define role access patterns by field type and name
    ADMIN_ONLY = ["admin"]
    ADMIN_ACCOUNTANT = ["admin", "accountant"]
    ADMIN_DOCTOR = ["admin", "doctor"]
    ADMIN_DOCTOR_NURSE = ["admin", "doctor", "nurse"]
    ALL_ROLES = ["admin", "doctor", "nurse", "reception", "accountant"]
    
    for code, info in ids.items():
        original = info["original"].lower()
        id_type = info["type"]
        dataset = info.get("dataset", "").lower()
        
        # Determine permissions based on field name + type + dataset
        perms = {"view": ALL_ROLES, "edit": ADMIN_DOCTOR_NURSE, "export": ADMIN_ONLY}
        
        # Financial fields — admin + accountant only
        if any(k in original for k in ["price", "cost", "fee", "salary", "invoice", "revenue", "expense", "profit", "bill"]):
            perms = {"view": ADMIN_ACCOUNTANT, "edit": ADMIN_ONLY, "export": ADMIN_ACCOUNTANT}
        
        # Patient medical data — admin + doctor + nurse
        elif any(k in original for k in ["diagnosis", "blood", "weight", "height", "prescription", "treatment"]):
            perms = {"view": ADMIN_DOCTOR_NURSE, "edit": ADMIN_DOCTOR, "export": ADMIN_DOCTOR}
        
        # Patient personal info — all staff
        elif any(k in original for k in ["name", "age", "gender", "phone", "address"]):
            perms = {"view": ALL_ROLES, "edit": ADMIN_DOCTOR_NURSE + ["reception"], "export": ADMIN_DOCTOR_NURSE}
        
        # Room/bed assignments — admin + nurse
        elif any(k in original for k in ["room", "bed", "floor", "capacity", "occupied"]):
            perms = {"view": ALL_ROLES, "edit": ADMIN_DOCTOR_NURSE, "export": ADMIN_ONLY}
        
        # Emergency data — admin + doctor + nurse
        elif any(k in original for k in ["emergency", "severity", "triage", "critical"]):
            perms = {"view": ADMIN_DOCTOR_NURSE, "edit": ADMIN_DOCTOR_NURSE, "export": ADMIN_ONLY}
        
        # Staff info — admin only
        elif any(k in original for k in ["password", "role", "username", "shift", "rating", "hire"]):
            perms = {"view": ADMIN_ONLY, "edit": ADMIN_ONLY, "export": ADMIN_ONLY}
        
        # Medicine stock — admin + nurse
        elif any(k in original for k in ["stock", "min_stock", "expiry", "supplier"]):
            perms = {"view": ADMIN_DOCTOR_NURSE, "edit": ADMIN_DOCTOR_NURSE, "export": ADMIN_ONLY}
        
        # Doctor info — admin + doctor (self)
        elif any(k in original for k in ["specialty", "patients_count", "doctor"]):
            perms = {"view": ALL_ROLES, "edit": ADMIN_ONLY, "export": ADMIN_DOCTOR}
        
        # Meta/project fields — admin only
        elif dataset == "_meta":
            perms = {"view": ADMIN_ONLY, "edit": ADMIN_ONLY, "export": ADMIN_ONLY}
        
        # Status fields — all can view, admin/doctor can edit
        elif "status" in original:
            perms = {"view": ALL_ROLES, "edit": ADMIN_DOCTOR, "export": ADMIN_DOCTOR_NURSE}
        
        # Canvas/Image fields — all can view, admin/doctor can edit
        elif id_type == "Canvas" or id_type == "URL":
            perms = {"view": ALL_ROLES, "edit": ADMIN_DOCTOR, "export": ADMIN_DOCTOR}
        
        # Boolean fields — admin + doctor can toggle
        elif id_type == "Boolean":
            perms = {"view": ALL_ROLES, "edit": ADMIN_DOCTOR, "export": ADMIN_ONLY}
        
        # Array/Object — admin can export, all can view
        elif id_type in ("Array", "Object"):
            perms = {"view": ALL_ROLES, "edit": ADMIN_ONLY, "export": ADMIN_ONLY}
        
        matrix[code] = perms
    
    return matrix


def generate_rbac_engine_js(rbac_matrix: dict) -> str:
    """Generate rbac_engine.js from the RBAC matrix."""
    matrix_json = json.dumps(rbac_matrix, ensure_ascii=False)
    
    return f'''// ═══════════════════════════════════════════════════════════════════════════
// RBAC Engine v2.1 — Role-Based Access Control
// Auto-generated by native_bridge.py (Phase 7)
// ═══════════════════════════════════════════════════════════════════════════
const RBACEngine = {{
    currentUserRole: 'admin', // Default: admin (set via login)
    matrix: {matrix_json},
    
    // ═══════════════════════════════════════════════════════════════════════
    // SET ROLE — Called after login
    // ═══════════════════════════════════════════════════════════════════════
    setRole(role) {{
        this.currentUserRole = role;
        this.applyPermissions();
    }},
    
    // ═══════════════════════════════════════════════════════════════════════
    // CHECK — Can user perform action on ID?
    // ═══════════════════════════════════════════════════════════════════════
    can(action, code) {{
        const perms = this.matrix[code];
        if (!perms) return true; // No restrictions = open
        const allowed = perms[action] || perms['view'];
        return allowed.includes(this.currentUserRole);
    }},
    
    // ═══════════════════════════════════════════════════════════════════════
    // APPLY — Hide/disable DOM elements based on role
    // ═══════════════════════════════════════════════════════════════════════
    applyPermissions() {{
        const elements = document.querySelectorAll('[data-code]');
        let hidden = 0, locked = 0;
        
        elements.forEach(el => {{
            const code = el.getAttribute('data-code');
            const perms = this.matrix[code];
            if (!perms) return;
            
            // Check 'view' permission
            if (!perms.view.includes(this.currentUserRole)) {{
                el.style.display = 'none';
                el.innerHTML = ''; // Security: scrub DOM to prevent inspect bypass
                hidden++;
                return;
            }}
            
            // Check 'edit' permission
            if (!perms.edit.includes(this.currentUserRole)) {{
                el.querySelectorAll('input, select, textarea').forEach(input => {{
                    input.setAttribute('readonly', 'true');
                    input.classList.add('rbac-readonly');
                }});
                locked++;
            }}
        }});
        
        console.log('[RBAC] Applied: ' + hidden + ' hidden, ' + locked + ' locked for role: ' + this.currentUserRole);
    }},
    
    // ═══════════════════════════════════════════════════════════════════════
    // LOGIN — Authenticate user + set role
    // ═══════════════════════════════════════════════════════════════════════
    async login(username, password) {{
        // In production: call backend API for JWT token
        // For now: hardcoded demo credentials
        const users = {{
            'admin': {{ password: 'admin123', role: 'admin' }},
            'doctor': {{ password: 'doc123', role: 'doctor' }},
            'nurse': {{ password: 'nurse123', role: 'nurse' }},
            'reception': {{ password: 'rec123', role: 'reception' }},
            'accountant': {{ password: 'acc123', role: 'accountant' }},
        }};
        
        const user = users[username];
        if (user && user.password === password) {{
            this.setRole(user.role);
            return {{ success: true, role: user.role }};
        }}
        return {{ success: false, error: 'Invalid credentials' }};
    }},
    
    // ═══════════════════════════════════════════════════════════════════════
    // LOGOUT
    // ═══════════════════════════════════════════════════════════════════════
    logout() {{
        this.currentUserRole = 'guest';
        this.applyPermissions();
    }},
}};

// Apply on DOM load
document.addEventListener('DOMContentLoaded', () => RBACEngine.applyPermissions());

// Export
if (typeof module !== 'undefined' && module.exports) module.exports = RBACEngine;
'''


