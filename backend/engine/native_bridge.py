def generate_native_files(config: dict, strings: dict, function_dir: Path) -> dict:
    """Generate native_bridge.js, rbac_engine.js, and offline_sync.js.
    
    Also updates strings.json with RBAC permissions.
    
    Args:
        config: The config.json dict
        strings: The strings.json dict
        function_dir: Path to write the JS files
        
    Returns:
        Dict with counts and file paths
    """
    results = {}
    
    # 1. Generate native_bridge.js
    (function_dir / "native_bridge.js").write_text(NATIVE_BRIDGE_JS, encoding="utf-8")
    results["native_bridge"] = len(NATIVE_BRIDGE_JS)
    print(f"[native_bridge] native_bridge.js ({len(NATIVE_BRIDGE_JS):,} chars)", flush=True)
    
    # 2. Generate RBAC matrix + rbac_engine.js
    rbac_matrix = generate_rbac_matrix(config, strings)
    rbac_js = generate_rbac_engine_js(rbac_matrix)
    (function_dir / "rbac_engine.js").write_text(rbac_js, encoding="utf-8")
    results["rbac_engine"] = len(rbac_js)
    results["rbac_rules"] = len(rbac_matrix)
    
    # 3. Update strings.json with RBAC permissions
    by_id = strings.get("by_id", {})
    for code, perms in rbac_matrix.items():
        if code in by_id:
            by_id[code]["permissions"] = perms
        else:
            by_id[code] = {"permissions": perms}
    strings["rbac_enabled"] = True
    strings["rbac_roles"] = ["admin", "doctor", "nurse", "reception", "accountant"]
    strings["rbac_rule_count"] = len(rbac_matrix)
    
    # Re-write strings.json with RBAC
    (function_dir / "strings.json").write_text(
        json.dumps(strings, indent=2, ensure_ascii=False), encoding="utf-8")
    results["strings_updated"] = True
    
    print(f"[rbac_engine] rbac_engine.js ({len(rbac_js):,} chars, {len(rbac_matrix)} rules)", flush=True)
    
    # 4. Generate offline_sync.js
