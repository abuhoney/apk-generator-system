# 2. LIST BUILDER
# ═══════════════════════════════════════════════════════════════════════════

class ListBuilder(BaseBuilder):
    """Builds repeatable data structures (Arrays, RecyclerViews, DataGrids)."""
    
    name = "list"
    dependencies = ["variables"]
    id_types = ["Array", "Object"]
    
    def build(self, config: dict, strings: dict, function_dir: Path) -> dict:
        ids = self.get_ids(config)
        manifests = []
        
        for code, info in ids.items():
            manifest = {
                "id": code,
                "field": info["original"],
                "dataset": info["dataset"],
                "type": info["type"],
                "adapter": "RecyclerView.Adapter" if info["type"] == "Array" else "CardAdapter",
                "item_layout": f"item_{info['original'].lower().replace(' ', '_')}",
            }
            manifests.append(manifest)
        
        (function_dir / "_lists_manifest.json").write_text(
            json.dumps(manifests, indent=2, ensure_ascii=False), encoding="utf-8")
        
        print(f"[ListBuilder] {len(manifests)} list manifests", flush=True)
        return {"lists": len(manifests)}


