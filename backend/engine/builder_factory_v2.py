# BUILDER FACTORY + REGISTRY
# ═══════════════════════════════════════════════════════════════════════════

class BuilderFactory:
    """Factory + Registry for all builders.
    
    Implements the Factory Pattern (creates builders by name) and
    Registry Pattern (builders register themselves).
    
    Adding a new builder (e.g., AI_builder) requires ZERO changes to existing code:
    1. Create a new class extending BaseBuilder
    2. Set its `name`, `dependencies`, `id_types`
    3. Register it: factory.register(MyBuilder())
    """
    
    def __init__(self):
        self._registry: dict[str, BaseBuilder] = {}
    
    def register(self, builder: BaseBuilder) -> None:
        """Register a builder instance."""
        self._registry[builder.name] = builder
        print(f"[BuilderFactory] Registered: {builder.name}", flush=True)
    
    def register_all(self) -> None:
        """Register all 10 built-in builders."""
        self.register(VariablesBuilder())
        self.register(ListBuilder())
        self.register(ControlBuilder())
        self.register(OperatorBuilder())
        self.register(FileBuilder())
        self.register(ViewBuilder())
        self.register(MathBuilder())
        self.register(ComponentBuilder())
        self.register(XmlStringsBuilder())
        self.register(MoreBlockBuilder())
    
    def get_builder(self, name: str) -> Optional[BaseBuilder]:
        """Get a builder by name."""
        return self._registry.get(name)
    
    def run_builder(self, name: str, config: dict, strings: dict, function_dir: Path) -> Optional[dict]:
        """Run a single builder by name."""
        builder = self._registry.get(name)
        if not builder:
            print(f"[BuilderFactory] Builder '{name}' not found!", flush=True)
            return None
        return builder.build(config, strings, function_dir)
    
    def _resolve_order(self) -> list[str]:
        """Resolve builder execution order based on dependencies (topological sort)."""
        # Simple dependency resolution
        order = []
        added = set()
        
        for _ in range(10):  # Max 10 iterations
            for name, builder in self._registry.items():
                if name in added:
                    continue
                # Check if all dependencies are already added
                deps_met = all(d in added for d in builder.dependencies)
                if deps_met:
                    order.append(name)
                    added.add(name)
        
        # Add any remaining (circular deps or unresolvable)
        for name in self._registry:
            if name not in added:
                order.append(name)
                added.add(name)
        
        return order
    
    def run_all(self, config: dict, strings: dict, function_dir: Path) -> dict:
        """Run all builders in dependency order.
        
        Returns a dict mapping builder name -> result.
        """
        order = self._resolve_order()
        print(f"[BuilderFactory] Execution order: {', '.join(order)}", flush=True)
        
        results = {}
        for name in order:
            try:
                result = self.run_builder(name, config, strings, function_dir)
                results[name] = result
            except Exception as e:
                print(f"[BuilderFactory] Builder '{name}' FAILED: {e}", flush=True)
                results[name] = {"error": str(e)}
        
        # Generate unified manifest
        manifest = {
            "builders_run": list(results.keys()),
            "total_builders": len(order),
            "results": results,
            "config_ids": config.get("total_ids", 0),
            "config_datasets": config.get("total_datasets", 0),
            "config_items": config.get("total_items", 0),
        }
        (function_dir / "_build_manifest.json").write_text(
            json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8")
        
        print(f"[BuilderFactory] Pipeline complete: {len(order)} builders, {sum(1 for r in results.values() if r and 'error' not in r)} succeeded", flush=True)
        return results


