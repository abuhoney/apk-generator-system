# 6. VIEW BUILDER (The Largest Builder)
# ═══════════════════════════════════════════════════════════════════════════

class ViewBuilder(BaseBuilder):
    """The largest builder. Generates layouts, widgets, and visual structure.
    
    Reads the `View` section from strings.json for each ID and produces
    layout XML + HTML + CSS.
    """
    
    name = "view"
    dependencies = ["variables"]
    id_types = []  # Processes all IDs
    
    def build(self, config: dict, strings: dict, function_dir: Path) -> dict:
        ids = config.get("ids", {})
        by_id = strings.get("by_id", {})
        
        layouts = {}
        html_widgets = []
        css_rules = []
        
        for code, info in ids.items():
            original = info["original"]
            id_type = info["type"]
            widget = info["widget"]
            
            # Get View config from strings.json
            view_config = by_id.get(code, {}).get("View", {})
            layout_type = view_config.get("layout", "linear_vertical")
            properties = view_config.get("properties", {})
            libraries = view_config.get("libraries", ["AndroidX"])
            
            # Generate XML layout
            xml_id = original.lower().replace(" ", "_")
            xml = self._build_xml(widget, xml_id, properties, layout_type)
            layout_name = f"item_{xml_id}"
            layouts[layout_name] = xml
            
            # Generate HTML widget
            html_widgets.append(self._build_html_widget(code, original, widget, id_type, properties))
            
            # Generate CSS
            css_rules.append(self._build_css(code, widget, id_type))
        
        # Write layouts
        layout_dir = function_dir / "_generated_layouts"
        layout_dir.mkdir(exist_ok=True)
        for name, xml in layouts.items():
            (layout_dir / f"{name}.xml").write_text(xml, encoding="utf-8")
        
        # Write HTML fragments
        html_content = f"<!-- Auto-generated by ViewBuilder -->\n<!-- Total widgets: {len(html_widgets)} -->\n\n" + "\n\n".join(html_widgets)
        (function_dir / "_view_fragments.html").write_text(html_content, encoding="utf-8")
        
        # Write CSS
        css_content = f"/* Auto-generated by ViewBuilder */\n\n" + "\n".join(css_rules)
        (function_dir / "_view_styles.css").write_text(css_content, encoding="utf-8")
        
        print(f"[ViewBuilder] {len(layouts)} XML layouts, {len(html_widgets)} HTML widgets", flush=True)
        return {"layouts": len(layouts), "widgets": len(html_widgets)}
    
    def _build_xml(self, widget: str, xml_id: str, props: dict, layout: str) -> str:
        orientation = "vertical" if "vertical" in layout else "horizontal"
        hint = props.get("hint", xml_id)
        input_type = props.get("input_type", "text")
        
        if widget == "EditText":
            return f'''<?xml version="1.0" encoding="utf-8"?>
<LinearLayout xmlns:android="http://schemas.android.com/apk/res/android"
    android:layout_width="match_parent" android:layout_height="wrap_content"
    android:orientation="{orientation}" android:padding="8dp">
    <EditText android:id="@+id/{xml_id}"
        android:layout_width="match_parent" android:layout_height="wrap_content"
        android:hint="{hint}" android:inputType="{input_type}" />
</LinearLayout>'''
        elif widget == "Spinner":
            return f'''<?xml version="1.0" encoding="utf-8"?>
<LinearLayout xmlns:android="http://schemas.android.com/apk/res/android"
    android:layout_width="match_parent" android:layout_height="wrap_content"
    android:orientation="{orientation}" android:padding="8dp">
    <Spinner android:id="@+id/{xml_id}"
        android:layout_width="match_parent" android:layout_height="wrap_content" />
</LinearLayout>'''
        elif widget == "Switch":
            return f'''<?xml version="1.0" encoding="utf-8"?>
<LinearLayout xmlns:android="http://schemas.android.com/apk/res/android"
    android:layout_width="match_parent" android:layout_height="wrap_content"
    android:orientation="{orientation}" android:padding="8dp">
    <Switch android:id="@+id/{xml_id}"
        android:layout_width="wrap_content" android:layout_height="wrap_content"
        android:text="{props.get("text", xml_id)}" />
</LinearLayout>'''
        elif widget == "ImageView":
            return f'''<?xml version="1.0" encoding="utf-8"?>
<FrameLayout xmlns:android="http://schemas.android.com/apk/res/android"
    android:layout_width="match_parent" android:layout_height="wrap_content"
    android:padding="8dp">
    <ImageView android:id="@+id/{xml_id}"
        android:layout_width="match_parent" android:layout_height="200dp"
        android:scaleType="centerCrop" />
</FrameLayout>'''
        else:
            return f'''<?xml version="1.0" encoding="utf-8"?>
<TextView xmlns:android="http://schemas.android.com/apk/res/android"
    android:id="@+id/{xml_id}"
    android:layout_width="match_parent" android:layout_height="wrap_content"
    android:padding="8dp" android:text="{hint}" />'''
    
    def _build_html_widget(self, code: str, original: str, widget: str, id_type: str, props: dict) -> str:
        hint = props.get("hint", original)
        input_type = props.get("input_type", "text")
        
        if widget == "EditText":
            return f'<div class="field-group" data-id="{code}">\n  <label>{original}</label>\n  <input type="{input_type}" id="{code}" placeholder="{hint}" class="form-input">\n</div>'
        elif widget == "Spinner":
            return f'<div class="field-group" data-id="{code}">\n  <label>{original}</label>\n  <select id="{code}" class="form-select">\n    <option value="">Select {original}</option>\n  </select>\n</div>'
        elif widget == "Switch":
            return f'<div class="field-group" data-id="{code}">\n  <label>{original}</label>\n  <label class="switch">\n    <input type="checkbox" id="{code}">\n    <span class="slider"></span>\n  </label>\n</div>'
        elif widget == "ImageView":
            return f'<div class="field-group" data-id="{code}">\n  <label>{original}</label>\n  <img id="{code}" src="" alt="{original}" class="form-image">\n</div>'
        else:
            return f'<div class="field-group" data-id="{code}">\n  <label>{original}</label>\n  <span id="{code}" class="form-text">{hint}</span>\n</div>'
    
    def _build_css(self, code: str, widget: str, id_type: str) -> str:
        return f'.field-group[data-id="{code}"] {{ margin-bottom: 12px; }}\n.field-group[data-id="{code}"] label {{ display:block; font-size:11px; color:#8b949e; margin-bottom:4px; }}'


