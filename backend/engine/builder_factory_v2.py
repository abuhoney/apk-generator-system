"""
builder_factory_v2.py — Factory + Registry Pattern for the 10 Builders.

This module implements two design patterns:
1. **Registry Pattern**: Each builder registers itself at import time.
2. **Factory Pattern**: The `BuilderFactory` creates the right builder by name.

This allows adding new builders (e.g., AI_builder.py) without touching existing code.

Usage:
    from engine.builder_factory_v2 import BuilderFactory
    
    factory = BuilderFactory()
    factory.register_all()  # Auto-registers all 10 builders
    
    # Run a specific builder
    factory.run_builder("variables", config, strings, function_dir)
    
    # Run all builders in dependency order
    results = factory.run_all(config, strings, function_dir)
"""
from __future__ import annotations

import abc
import json
from pathlib import Path
from typing import Any, Optional


# ═══════════════════════════════════════════════════════════════════════════
# ABSTRACT BASE BUILDER
# ═══════════════════════════════════════════════════════════════════════════

class BaseBuilder(abc.ABC):
    """Abstract base class for all builders.
    
    Every builder MUST:
    1. Have a unique `name` attribute
    2. Implement `build()` method
    3. Declare its `dependencies` (other builder names that must run first)
    4. Declare which `id_types` it handles
    """
    
    name: str = "base"
    dependencies: list[str] = []  # Builder names that must run before this one
    id_types: list[str] = []     # Which ID types this builder processes (empty = all)
    
    @abc.abstractmethod
    def build(self, config: dict, strings: dict, function_dir: Path) -> dict:
        """Execute this builder on the given config + strings.
        
        Args:
            config: The config.json dict (The Map)
            strings: The strings.json dict (The Execution Matrix)
            function_dir: Path to the function folder
            
        Returns:
            A dict with builder-specific results (manifests, counts, etc.)
        """
        ...
    
    def can_process(self, id_info: dict) -> bool:
        """Check if this builder should process a given ID.
        
        If `id_types` is empty, the builder processes ALL IDs.
        Otherwise, it only processes IDs whose type is in `id_types`.
        """
        if not self.id_types:
            return True
        return id_info.get("type", "") in self.id_types
    
    def get_ids(self, config: dict) -> dict:
        """Get all IDs that this builder should process."""
        return {
            code: info for code, info in config.get("ids", {}).items()
            if self.can_process(info)
        }


