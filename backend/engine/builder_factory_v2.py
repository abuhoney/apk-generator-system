# 1. VARIABLES BUILDER
# ═══════════════════════════════════════════════════════════════════════════

class VariablesBuilder(BaseBuilder):
    """Converts fields to programmatic variables (String, Int, Boolean) with initialization."""
    
    name = "variables"
    dependencies = []
    id_types = ["String", "Int", "Float", "Boolean", "Email", "Phone", "URL", "Date", "Enum"]
    
    def build(self, config: dict, strings: dict, function_dir: Path) -> dict:
        ids = self.get_ids(config)
        java_vars = []
        js_vars = []
        
        for code, info in ids.items():
            original = info["original"]
            id_type = info["type"]
            
            # Java variable
            java_type = {
                "String": "String", "Email": "String", "Phone": "String", "URL": "String",
                "Date": "String", "Enum": "String",
                "Int": "int", "Float": "double", "Boolean": "boolean",
            }.get(id_type, "String")
            java_name = original.lower().replace(" ", "_").replace("-", "_")
            java_vars.append(f"    // ID: {code} | Field: {original} | Type: {id_type}\n    {java_type} {java_name};")
            
            # JS variable
            js_vars.append(f"  // ID: {code} | Field: {original}\n  let {code} = {self._default_js(id_type)};")
        
        # Write generated files
        java_content = f"// Auto-generated by VariablesBuilder\n// Total variables: {len(java_vars)}\n\n" + "\n\n".join(java_vars)
        js_content = f"// Auto-generated by VariablesBuilder\n// Total variables: {len(js_vars)}\n\n" + "\n\n".join(js_vars)
        
        (function_dir / "_variables.java").write_text(java_content, encoding="utf-8")
        (function_dir / "_variables.js").write_text(js_content, encoding="utf-8")
        
        # Update strings.json with variable declarations
        for code in ids:
            if code in strings.get("by_id", {}):
                oncreate = strings["by_id"][code].get("OnCreate", {})
                if "Variables" in oncreate:
                    # Already set by data_analyzer_v2, keep it
                    pass
        
        print(f"[VariablesBuilder] {len(java_vars)} Java vars, {len(js_vars)} JS vars", flush=True)
        return {"java_vars": len(java_vars), "js_vars": len(js_vars)}
    
    def _default_js(self, id_type: str) -> str:
        return {"String": "''", "Int": "0", "Float": "0.0", "Boolean": "false"}.get(id_type, "null")


