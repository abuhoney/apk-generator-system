# 3. CONTROL BUILDER
# ═══════════════════════════════════════════════════════════════════════════

class ControlBuilder(BaseBuilder):
    """Generates control logic (If/Else, Switch, For/While) from field types."""
    
    name = "control"
    dependencies = ["variables"]
    id_types = []  # Processes all IDs (control logic applies to everything)
    
    def build(self, config: dict, strings: dict, function_dir: Path) -> dict:
        ids = config.get("ids", {})
        control_blocks = []
        
        for code, info in ids.items():
            original = info["original"]
            id_type = info["type"]
            
            block = {"id": code, "field": original, "logic": []}
            
            if id_type in ("String", "Email", "Phone"):
                block["logic"].append({
                    "type": "if",
                    "condition": f"{code}.length < 3",
                    "action": f"showError('Invalid {original}')",
                })
            elif id_type == "Int":
                block["logic"].append({
                    "type": "if",
                    "condition": f"{code} < 0",
                    "action": f"showError('{original} must be positive')",
                })
            elif id_type == "Enum":
                block["logic"].append({
                    "type": "switch",
                    "variable": code,
                    "cases": [],
                })
            
            # Add loop for array datasets
            if id_type == "Array":
                block["logic"].append({
                    "type": "for",
                    "variable": "item",
                    "iterable": code,
                    "body": f"render_item(item)",
                })
            
            control_blocks.append(block)
        
        (function_dir / "_control_manifest.json").write_text(
            json.dumps(control_blocks, indent=2, ensure_ascii=False), encoding="utf-8")
        
        print(f"[ControlBuilder] {len(control_blocks)} control blocks", flush=True)
        return {"blocks": len(control_blocks)}


