def run_pipeline(function_dir: Path, project_name: str = "UniversalApp") -> dict:
    """Run the full v2 pipeline: data_analyzer_v2 + BuilderFactory.
    
    Args:
        function_dir: Path to the function folder
        project_name: Optional project name
        
    Returns:
        Dict with all builder results
    """
    # Phase 1: Analyze data
    from engine.data_analyzer_v2 import analyze_data_files
    config, strings = analyze_data_files(function_dir, project_name)
    
    # Phase 2: Run all builders
    factory = BuilderFactory()
    factory.register_all()
    results = factory.run_all(config, strings, function_dir)
    
    return {"config": config, "strings": strings, "builders": results}


