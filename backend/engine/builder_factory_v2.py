class MathBuilder(BaseBuilder):
    """Links Canvas operations (Fabric.js/Konva.js) with math equations."""
    
    name = "math"
    dependencies = ["variables"]
    id_types = ["Int", "Float", "Canvas"]
    
    def build(self, config: dict, strings: dict, function_dir: Path) -> dict:
        ids = self.get_ids(config)
        formulas = []
        
        for code, info in ids.items():
            original = info["original"].lower()
            id_type = info["type"]
            
            if id_type in ("Int", "Float"):
                if "price" in original or "cost" in original or "fee" in original:
                    formulas.append({"id": code, "field": info["original"], "formula": f"{code} * 1.15", "description": "Calculate with VAT"})
                if "weight" in original and "height" in str(ids.keys()):
                    formulas.append({"id": code, "field": info["original"], "formula": f"weight / Math.pow(height/100, 2)", "description": "BMI calculation"})
        
        (function_dir / "_math_manifest.json").write_text(
            json.dumps(formulas, indent=2, ensure_ascii=False), encoding="utf-8")
        
        print(f"[MathBuilder] {len(formulas)} formulas", flush=True)
        return {"formulas": len(formulas)}


