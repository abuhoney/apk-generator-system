# 9. XML STRINGS BUILDER
# ═══════════════════════════════════════════════════════════════════════════

class XmlStringsBuilder(BaseBuilder):
    """Generates native config files (strings.xml, AndroidManifest.xml)."""
    
    name = "xml_strings"
    dependencies = ["variables"]
    id_types = []  # Processes all IDs
    
    def build(self, config: dict, strings: dict, function_dir: Path) -> dict:
        ids = config.get("ids", {})
        by_id = strings.get("by_id", {})
        xml_entries = []
        
        for code, info in ids.items():
            original = info["original"]
            android_name = original.lower().replace(" ", "_").replace("-", "_")
            
            # Add label string
            xml_entries.append(f'    <string name="{android_name}_label">{original}</string>')
            
            # Add values from strings.json
            values = by_id.get(code, {}).get("values", [])
            for v in values[:10]:  # Limit to 10 per field
                val = str(v.get("text", "")).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
                xml_entries.append(f'    <string name="{android_name}_{v.get("item_index", 0)}">{val}</string>')
        
        xml_content = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Auto-generated by XmlStringsBuilder -->
<!-- {len(xml_entries)} strings from {len(ids)} IDs -->
<resources>
{chr(10).join(xml_entries)}
</resources>'''
        
        (function_dir / "_final_strings.xml").write_text(xml_content, encoding="utf-8")
        
        print(f"[XmlStringsBuilder] {len(xml_entries)} XML strings", flush=True)
        return {"xml_strings": len(xml_entries)}


