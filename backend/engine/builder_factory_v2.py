# 5. FILE BUILDER
# ═══════════════════════════════════════════════════════════════════════════

class FileBuilder(BaseBuilder):
    """Links file upload interfaces to Web APIs (FileReader, IndexedDB, Capacitor)."""
    
    name = "file"
    dependencies = []
    id_types = ["URL", "Canvas"]
    
    def build(self, config: dict, strings: dict, function_dir: Path) -> dict:
        ids = self.get_ids(config)
        file_defs = []
        
        media_dir = function_dir / "media"
        if media_dir.exists():
            for f in sorted(media_dir.iterdir()):
                if f.is_file():
                    file_defs.append({
                        "name": f.name,
                        "path": f"file:///android_asset/webapp/media/{f.name}",
                        "size": f.stat().st_size,
                        "ext": f.suffix.lower(),
                    })
        
        (function_dir / "_files_manifest.json").write_text(
            json.dumps(file_defs, indent=2, ensure_ascii=False), encoding="utf-8")
        
        print(f"[FileBuilder] {len(file_defs)} files registered", flush=True)
        return {"files": len(file_defs)}


